import numpy as np
import matplotlib.pyplot as plt
y=np.ones(5)
plt.stem(y)
plt.title('Input signal')
plt.show()
N=len(y)
n=np.arange(N)
k=n.reshape((N,1))
exp_term=np.exp(-2j*np.pi*k*n/N)
decomp=np.dot(exp_term,y)
plt.stem(np.real(decomp))
plt.title('Output signal from decomposition')
plt.show()
Y_fft=np.fft.fft(y)
plt.stem(np.abs(Y_fft))
plt.title('Magnitude of fourier coefficents using built-in FFT')
plt.show()
diff=np.abs(Y_fft)-np.abs(decomp)
plt.stem(diff)
plt.title('Difference between the output siganl and the FFT results')
plt.show() 